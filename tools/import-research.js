// One-off importer: turns ../research/wilds-tutorials-batch-*.md into wilds/tutorials-content.js.
// Re-run after editing the research notes, then re-run build-tutorials.js.
const fs = require('fs');
const path = require('path');

const researchDir = path.resolve(__dirname, '../../research');
const outFile = path.resolve(__dirname, '../wilds/tutorials-content.js');

const FIELD_MAP = {
  'Fight overview': 'overview',
  'Key mechanics': 'mechanics',
  'Dangerous attacks / tells': 'tells',
  'Punish windows / strategy': 'strategy',
  'Element/status weaknesses': 'element',
  'Breakable parts / wounds': 'parts',
  'Recommended skills/items': 'items',
  'Update/variant notes': 'update',
  Confidence: 'confidence',
  Sources: 'sources',
};

const clean = (value) => String(value)
  .replace(/\*\*/g, '')
  .replace(/\s+/g, ' ')
  .trim();

const parseField = (block) => {
  const entries = [];
  let open = null;
  for (const line of block.split(/\r?\n/)) {
    if (!line.trim() || line.trim() === '---') continue;
    const bullet = line.match(/^\s*-\s+(.*)$/);
    const numbered = line.match(/^\s*\d+\.\s+(.*)$/);
    if (numbered) {
      open = { type: 'source', value: numbered[1] };
      entries.push(open);
    } else if (bullet) {
      open = { type: 'bullet', value: bullet[1] };
      entries.push(open);
    } else if (!/^\s/.test(line) || !open) {
      // Unindented line: value of a single-line field, or a wrapped line.
      if (open && open.type === 'text') open.value += ` ${line.trim()}`;
      else {
        open = { type: 'text', value: line.trim() };
        entries.push(open);
      }
    } else {
      open.value += ` ${line.trim()}`;
    }
  }
  return entries;
};

const monsters = {};

for (const batch of [1, 2, 3, 4]) {
  const file = path.join(researchDir, `wilds-tutorials-batch-${batch}.md`);
  const text = fs.readFileSync(file, 'utf8');
  const sections = text.split(/^## /m).slice(1);

  for (const section of sections) {
    const [rawName, ...rest] = section.split(/\r?\n/);
    const name = rawName.trim();
    if (!name || /^coverage table/i.test(name)) continue;

    const body = rest.join('\n');
    // Split on top-level "- Field:" lines only.
    const fieldBlocks = {};
    let currentField = null;
    let buffer = [];
    const flush = () => {
      if (currentField) fieldBlocks[currentField] = buffer.join('\n');
      buffer = [];
    };
    for (const line of body.split(/\r?\n/)) {
      const field = line.match(/^-\s+([^:]+):\s*(.*)$/);
      if (field) {
        flush();
        currentField = field[1].trim();
        buffer = [field[2]];
      } else if (currentField) {
        buffer.push(line);
      }
    }
    flush();

    const entry = { confidence: 'medium', sources: [] };
    for (const [label, raw] of Object.entries(fieldBlocks)) {
      const key = FIELD_MAP[label];
      if (!key) continue;
      const parsed = parseField(raw);
      if (key === 'sources') {
        entry.sources = parsed
          .filter((item) => item.type === 'source')
          .map((item) => {
            const url = (item.value.match(/https?:\/\/\S+/) || [])[0];
            return url ? url.replace(/[.,;]+$/, '') : null;
          })
          .filter(Boolean);
      } else if (key === 'mechanics' || key === 'tells' || key === 'strategy') {
        entry[key] = parsed.map((item) => clean(item.value)).filter(Boolean);
      } else {
        entry[key] = clean(parsed.map((item) => item.value).join(' '));
      }
    }

    const normalized = (entry.confidence || '').toLowerCase();
    entry.confidence = normalized.includes('medium-high') ? 'medium-high'
      : normalized.startsWith('high') ? 'high'
        : normalized.startsWith('low') ? 'low'
          : 'medium';

    for (const key of ['overview', 'element', 'parts', 'items', 'update']) {
      if (!entry[key]) throw new Error(`${name}: missing ${key}`);
    }
    for (const key of ['mechanics', 'tells', 'strategy']) {
      if (!entry[key] || !entry[key].length) throw new Error(`${name}: missing ${key}`);
    }
    if (!entry.sources.length) throw new Error(`${name}: missing sources`);

    // Link text = host + path, without protocol.
    entry.sources = entry.sources.map((url) => {
      const parsed = new URL(url);
      return { url, label: decodeURIComponent(parsed.hostname + parsed.pathname).replace(/\/$/, '') };
    });

    monsters[name] = entry;
  }
}

if (Object.keys(monsters).length !== 34) {
  throw new Error(`Expected 34 monsters, parsed ${Object.keys(monsters).length}`);
}

const output = `// Generated by tools/import-research.js from the research notes. Do not edit by hand.\nconst tutorialContent = ${JSON.stringify(monsters, null, 2)};\n`;
fs.writeFileSync(outFile, output, 'utf8');
console.log(`Wrote ${Object.keys(monsters).length} entries to ${path.relative(process.cwd(), outFile)}`);
